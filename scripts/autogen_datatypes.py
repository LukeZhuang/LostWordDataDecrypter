import re

INDENT = "    "


def get_class_content(class_line_num, lines):
	result = {}
	for class_name in class_line_num:
		class_result = []
		line_num = class_line_num[class_name]
		assert lines[line_num + 1] == '{'
		if lines[line_num - 1] != '// Namespace:':
			assert lines[line_num - 1] == '[Serializable]'
			class_result.append('[Serializable]')
		class_result.append(lines[line_num])
		class_result.append('{')
		if lines[line_num + 2] == '// Fields':
			class_result.append(INDENT + '// Fields')
			i = line_num + 3
			mpm = None
			while lines[i].startswith('public') or lines[i].startswith('private') or lines[i].startswith('protected') or lines[i].startswith('[MessagePackMember'):
				if 'static DelegateBridge' in lines[i] or 'XLua_Gen_Delegate' in lines[i]:
					i += 1
					continue
				if lines[i].startswith('[MessagePackMember'):
					mpm = lines[i]
				else:
					if lines[i].startswith('public') and mpm != None:
						class_result.append(INDENT + mpm)
						class_result.append(INDENT + lines[i])
					else:
						class_result.append(INDENT + lines[i])
					mpm = None
				i += 1
		class_result.append('}')
		result[class_name] = class_result
	return result


f = open('dump.cs')
lines = []
master_line_num = {}
table_line_num = {}
record_line_num = {}
for (idx, line) in enumerate(f):
	l = line.strip()
	lines.append(l)
	master_gp = re.findall("class ([a-zA-Z]+)Master", l)
	table_gp = re.findall("class ([a-zA-Z]+)Table : MasterTable", l)
	record_gp = re.findall("class ([a-zA-Z]+)Record : [a-zA-Z]+Record", l)
	if len(master_gp) > 0:
		master_line_num[master_gp[0]] = idx
	if len(table_gp) > 0:
		table_line_num[table_gp[0]] = idx
	if len(record_gp) > 0:
		record_line_num[record_gp[0]] = idx

# print(len(master_line_num.items()))
# print(len(table_line_num.items()))
# print(len(record_line_num.items()))

masters = get_class_content(master_line_num, lines)
tables = get_class_content(table_line_num, lines)
records = get_class_content(record_line_num, lines)

def str_wrapper(s):
	return re.sub(' // TypeDefIndex:.*', '', s)

for k in record_line_num:
	assert k in table_line_num
	assert k in master_line_num

for k in table_line_num:
	assert k in master_line_num

for k in master_line_num:
	fo = open("output/" + k + "Master.cs", "w")
	fo.write("/* THIS FILE IS AUTOMATICALLY GENERATED */\n")
	fo.write("using MsgPack.Serialization;\n")
	fo.write("using System;\n")
	fo.write("using System.Collections.Generic;\n")
	fo.write("\n")
	fo.write("namespace LostWordDataDecrypter.DataTypes.DataTypes\n")
	fo.write("{\n")
	if k in records:
		for l in records[k]:
			fo.write(INDENT + str_wrapper(l) + "\n")
	fo.write("\n")
	if k in tables:
		for l in tables[k]:
			fo.write(INDENT + str_wrapper(l) + "\n")
	fo.write("\n")
	if k in masters:
		for l in masters[k]:
			fo.write(INDENT + str_wrapper(l) + "\n")
	fo.write("\n")
	fo.write("}\n")
	fo.close()
